const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
// Run against Astro dev: production deliberately retains the existing owner authentication gate.
const base = process.env.PREVIEW_URL || 'http://localhost:4321';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Editor test must use a local preview; never run against a published editor.');
const output = process.env.PREVIEW_EVIDENCE || '/tmp/codeverse-evidence';
const {mkdirSync} = await import('node:fs'); mkdirSync(output,{recursive:true});
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const pageErrors = [];
page.on('pageerror',e=>pageErrors.push(e.message));
await page.addInitScript(()=>{localStorage.setItem('visual-theme','poetize');localStorage.setItem('theme','light');});
await page.goto(base+'/notes/',{waitUntil:'networkidle'});
await page.locator('#notes-app[data-ready]').waitFor();
await page.locator('[data-action="new"]').first().click();
await page.locator('#notes-title').fill('即时编辑体验');
await page.locator('[data-view="edit"]').click();
const body='# 一级标题\n\n中文段落与 **粗体**、[链接](https://example.com)。\n\n- 项目一\n- 项目二\n\n> 引用内容\n\n```js\nconst hello = "世界";\n```\n\n![海岸](/favicon.svg)\n\n| 列 | 值 |\n| --- | --- |\n| A | B |\n';
await page.locator('#notes-body').fill(body);
await page.locator('[data-view="live"]').click();
await page.locator('#notes-live h1').waitFor();
assert.equal(await page.locator('#notes-live h1').textContent(),'一级标题');
assert.equal(await page.locator('#notes-live strong').textContent(),'粗体');
assert.equal(await page.locator('#notes-live li').count(),2);
assert.equal(await page.locator('#notes-live blockquote').count(),1);
assert.equal(await page.locator('#notes-live pre').count(),1);
assert.equal(await page.locator('#notes-live table').count(),1);
assert.equal(await page.locator('#notes-live img').count(),1);
await page.locator('#notes-live strong').click();
const input=page.locator('.notes-live__input');
await input.press('End');
await input.pressSequentially(' added');
await input.press('Control+Enter');
assert.ok((await page.locator('#notes-body').inputValue()).includes(' added'));
await page.locator('[data-view="edit"]').click();
const edited=await page.locator('#notes-body').inputValue();
await page.locator('[data-view="live"]').click();
assert.equal(await page.locator('#notes-body').inputValue(),edited);
await page.locator('#notes-live strong').click();
await input.press('Control+z');
assert.notEqual(await page.locator('#notes-body').inputValue(),edited);
await input.press('Control+Shift+z');
assert.equal(await page.locator('#notes-body').inputValue(),edited);
// IME composition does not replace the active control.
await input.evaluate(a=>{a.dataset.ime='original';a.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));a.value+='中文输入\n\n';a.dispatchEvent(new InputEvent('input',{bubbles:true,isComposing:true}));});
assert.equal(await input.getAttribute('data-ime'),'original');
await input.evaluate(a=>a.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true})));
assert.ok((await page.locator('#notes-body').inputValue()).includes('中文输入'));
await input.press('Control+Enter');
// Toolbar operates on the full, exact source, with selection from the live block.
await page.locator('#notes-live h1').click();
await input.evaluate(a=>{a.setSelectionRange(2,6);a.dispatchEvent(new Event('select'));});
await page.locator('[data-cmd="bold"]').click();
await page.waitForTimeout(80);
assert.ok((await page.locator('#notes-body').inputValue()).includes('**一级标题**'));
await page.locator('.notes-live__input').press('Control+Enter');
await page.locator('.notes-live__append').click();
await page.context().grantPermissions(['clipboard-read','clipboard-write']);
await page.evaluate(()=>navigator.clipboard.writeText('## Fresh heading'));
await page.locator('.notes-live__input').press('Control+v');
await page.locator('.notes-live__input').press('Enter');
await page.locator('.notes-live__input').press('Enter');
await page.locator('#notes-live h2').filter({hasText:'Fresh heading'}).waitFor();
await page.locator('.notes-live__input').press('Control+Enter');
await page.screenshot({path:output+'/notes-live-desktop.png'});
const before=await page.locator('#notes-body').inputValue();
// Switching to source shares document undo history, then redo restores all bytes.
await page.locator('[data-view="edit"]').click();
await page.locator('#notes-body').press('Control+z');
assert.notEqual(await page.locator('#notes-body').inputValue(),before);
await page.locator('#notes-body').press('Control+Shift+z');
assert.equal(await page.locator('#notes-body').inputValue(),before);
await page.locator('[data-view="live"]').click();
const downloadPromise=page.waitForEvent('download');
await page.locator('[data-action="download"]').evaluate(b=>b.click());
const download=await downloadPromise;
const exported=await readFile(await download.path(),'utf8');
assert.ok(exported.includes(before.trimEnd()));
await page.reload({waitUntil:'networkidle'});
await page.locator('#notes-app[data-ready]').waitFor();
assert.equal(await page.locator('#notes-body').inputValue(),before);
assert.equal(await page.locator('#notes-app').getAttribute('data-mode'),'live');
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(450);
if (await page.locator('#notes-app').evaluate(e=>e.classList.contains('is-drawer'))) await page.locator('.notes-sidebar__close').click();
await page.waitForTimeout(550);
await page.screenshot({path:output+'/notes-live-mobile.png'});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
console.log('PASS common blocks, inline edit, toolbar selection, clipboard paste, blankline render, source byte roundtrip + undo/redo, IME control preservation, exact-body Markdown export, local persistence, mobile width');
assert.deepEqual(pageErrors, []);
await browser.close();
