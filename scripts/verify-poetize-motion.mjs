import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.PREVIEW_URL||'http://127.0.0.2:4322';
const out=process.env.PREVIEW_EVIDENCE||'/tmp/poetize-motion';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});const checks=[];
await page.goto(base+'/?visual-theme=poetize');
await page.locator('.poetize-explore').click();await page.waitForTimeout(900);
const card=page.locator('.wall-card').first();await card.hover();await page.waitForTimeout(400);
assert.equal(await card.evaluate(el=>getComputedStyle(el).translate),'0px -4px');
await page.mouse.move(0,0);await card.focus();await page.keyboard.press('Tab');await page.keyboard.press('Shift+Tab');await page.waitForTimeout(1100);
assert.equal(await card.evaluate(el=>document.activeElement===el),true);
assert.notEqual(await card.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
await page.screenshot({path:out+'/desktop-motion.png'});
checks.push('Desktop hover lift and keyboard focus outline; screenshot captured');
await page.locator('#visual-theme-btn').click();
assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('visual-theme-changing')),true);
await page.waitForTimeout(500);assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('visual-theme-changing')),false);
await page.locator('#visual-theme-btn').click();await page.reload();
assert.equal(await page.locator('html').getAttribute('data-visual-theme'),'poetize');
checks.push('Theme transition class cleans up and preference survives reload');
await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
assert.equal(await page.locator('html').getAttribute('data-poetize-motion'),'off');
await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
assert.equal(await page.locator('html').getAttribute('data-poetize-motion'),'on');
checks.push('Simulated visibilitychange pauses and resumes decorative motion');
await page.goto(base+'/editor-preview/');
await page.locator('#demo-source').click();await page.locator('#demo-body').fill('# Motion regression\n\nDraft remains intact.');
await page.locator('#demo-body').focus();await page.evaluate(()=>document.querySelector('#visual-theme-btn').click());
assert.equal(await page.locator('#demo-body').evaluate(el=>document.activeElement===el),true);
assert.equal(await page.locator('#demo-body').inputValue(),'# Motion regression\n\nDraft remains intact.');
checks.push('Programmatic theme switch preserves editor focus and exact source');
await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base+'/?visual-theme=poetize');
assert.equal(await page.locator('html').getAttribute('data-poetize-motion'),'off');
await page.locator('#visual-theme-btn').click();assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('visual-theme-changing')),false);
checks.push('Reduced motion disables decorative motion and theme transition');
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
await mobile.goto(base+'/?visual-theme=poetize');await mobile.locator('.poetize-explore').tap();await mobile.waitForTimeout(900);
const mc=mobile.locator('.wall-card').first();assert.equal(await mc.evaluate(el=>getComputedStyle(el).translate),'none');
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await mobile.screenshot({path:out+'/mobile-motion.png'});
await Promise.all([mobile.waitForURL(url=>url.pathname!=='/'), mc.tap()]);
checks.push('Touch cards have no hover lift, remain navigable, and have no horizontal overflow');
writeFileSync(out+'/motion-results.json',JSON.stringify({checks},null,2));console.log(checks.join('\n'));await browser.close();
